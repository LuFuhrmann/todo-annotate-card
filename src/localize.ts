const TABLES: Record<string, Record<Key, string>> = { en, de };

export type Localizer = (key: Key, vars?: Record<string, string>) => string;

export function localizer(lang: string | undefined): Localizer {
  const table = TABLES[(lang ?? "en").split("-")[0].toLowerCase()] ?? en;
  return (key, vars) => {
    let s = table[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
    return s;
  };
}
